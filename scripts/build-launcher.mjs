/**
 * Build the tray launcher (tools/launcher) for one platform.
 *
 *   npm run build:launcher        # for this machine, into tools/launcher/bin/
 *
 * `scripts/package.mjs` builds it straight into a package, and `test/launcher.test.ts` into a
 * scratch folder to run it. Needs Go (https://go.dev/dl). A macOS build also needs Xcode's
 * command line tools, because the menu bar is reached through Cocoa.
 *
 * - **Windows**: a GUI-subsystem executable, so it opens no console, carrying the app's icon,
 *   its version, and a manifest declaring it DPI-aware -- otherwise Windows scales the tray icon
 *   up from 16px and it blurs. The resource is generated by go-winres (a Go tool pinned in
 *   go.mod), used for the build and deleted after.
 * - **macOS**: an `.app` bundle. `LSUIElement` makes it a menu bar item with no Dock icon and no
 *   app menu. It is signed ad hoc as a whole: an unsigned bundle downloaded on Apple silicon is
 *   reported as damaged, where an ad-hoc one gets the ordinary Open Anyway.
 * - **Linux**: a plain executable. No cgo: the tray is spoken to over D-Bus.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defaultRid } from './build-pp-helper.mjs';
import { trayLauncherFor } from './package-files.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const launcherSource = path.join(root, 'tools', 'launcher');

/** Go's names for a .NET runtime identifier's system and architecture. */
export function goTarget(rid) {
  const [os, arch] = rid.split('-');
  const goos = { win: 'windows', osx: 'darwin', linux: 'linux' }[os];
  if (!goos) throw new Error(`no launcher build for ${rid}`);
  return { goos, goarch: arch === 'arm64' ? 'arm64' : 'amd64' };
}

/** The bundle's Info.plist. */
export function infoPlist(version) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>osu! local profiles</string>
  <key>CFBundleDisplayName</key><string>osu! local profiles</string>
  <key>CFBundleIdentifier</key><string>io.github.jonathant09.osu-local-profiles</string>
  <key>CFBundleExecutable</key><string>osu-local-profiles</string>
  <key>CFBundleIconFile</key><string>app.icns</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
`;
}

function go(args, env) {
  const result = spawnSync('go', args, {
    cwd: launcherSource,
    env: { ...process.env, ...env },
    encoding: 'utf8',
    timeout: 900_000,
  });
  if (result.error && result.error.code === 'ENOENT') {
    throw new Error('Go is not installed, and the tray launcher is written in it: https://go.dev/dl');
  }
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`go ${args.join(' ')} failed:\n${result.stdout}${result.stderr}`);
  return result.stdout;
}

/**
 * Build the launcher for `rid` into `outDir`, under the name its package gives it. Returns the
 * path of the executable itself -- inside the bundle, on macOS.
 */
export function buildLauncher(outDir, rid = defaultRid(), version = 'dev') {
  const hostOs = rid.split('-')[0];
  const { goos, goarch } = goTarget(rid);
  const tray = trayLauncherFor(hostOs);
  const executable = path.join(outDir, ...tray.executable.split('/'));
  fs.rmSync(path.join(outDir, tray.name), { recursive: true, force: true });
  fs.mkdirSync(path.dirname(executable), { recursive: true });

  const env = { GOOS: goos, GOARCH: goarch, CGO_ENABLED: goos === 'darwin' ? '1' : '0' };
  const ldflags = `-s -w -X main.version=${version}${goos === 'windows' ? ' -H windowsgui' : ''}`;

  const resources = () =>
    fs.readdirSync(launcherSource).filter((name) => /^rsrc_windows_.*\.syso$/.test(name));
  try {
    if (goos === 'windows') {
      go(
        [
          'tool', 'go-winres', 'simply',
          '--arch', goarch,
          '--out', 'rsrc',
          '--manifest', 'gui',
          '--icon', 'icon/app.png',
          '--product-name', 'osu! local profiles',
          '--file-description', 'osu! local profiles',
          '--original-filename', tray.name,
          // A Windows version resource wants numbers only; a development build has none.
          ...(/^\d+\.\d+\.\d+$/.test(version) ? ['--product-version', version, '--file-version', version] : []),
        ],
        env,
      );
    }
    go(['build', '-trimpath', '-ldflags', ldflags, '-o', executable, '.'], env);
  } finally {
    for (const name of resources()) fs.rmSync(path.join(launcherSource, name), { force: true });
  }

  if (goos === 'darwin') {
    const bundle = path.join(outDir, tray.name);
    fs.mkdirSync(path.join(bundle, 'Contents', 'Resources'), { recursive: true });
    fs.writeFileSync(path.join(bundle, 'Contents', 'Info.plist'), infoPlist(version));
    fs.copyFileSync(path.join(launcherSource, 'icon', 'app.icns'), path.join(bundle, 'Contents', 'Resources', 'app.icns'));
    const signed = spawnSync('codesign', ['--force', '--deep', '--sign', '-', bundle], { encoding: 'utf8' });
    if (signed.status !== 0) throw new Error(`signing the bundle failed: ${signed.stderr ?? signed.error}`);
  } else if (goos === 'linux') {
    fs.chmodSync(executable, 0o755);
  }
  return executable;
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();

if (invokedDirectly) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const out = path.join(launcherSource, 'bin');
  console.log(`  ${path.relative(root, buildLauncher(out, defaultRid(), pkg.version))}`);
}
